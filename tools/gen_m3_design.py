p.append("MILESTONES = [10, 25, 50, 100, 200, 300, 400, 500, 625, 1000, 1250]（工程方案 5.1 原表）。")
p.append("")
p.append("规则（每条带 once 去重，fired 集合按 match 生命周期）：")
p.append("- R-milestone-pre：layers == N-1 -> info「下一档奖励：{options}，还差 1 层」")
p.append("- R-milestone-hit：layers == N -> info「达成 {N} 层档：{options}」")
p.append("- R-stop：layers >= 500 and hp < 40 -> critical「500 分水岭+岩宝达标即停，别贪」")
p.append("- 奖励内容来自 rules.rewards（layers 匹配）；不在 rewards 的里程碑只提示层数")
p.append("")
p.append("## 4. 模块(2) 战力评分（power_score.py）")
p.append("")
p.append("```")
p.append("战力分(0-100) = 0.35*star + 0.25*trait + 0.25*item + 0.15*trend   # D5 初始权重")
p.append("star  = sum(unit_power) / board_max * 100")
p.append("        unit_power = (row.hp + 10*row.ad) / 1000，row 取 stars[min(star or 1, 3)-1]")
p.append("        board_max = 10 * max(all units star3 row_power)   # 从数值库加载期计算，无魔法常数")
p.append("trait = min(sum(min(count, 6) for active traits) * 1.5, 100)  # D1 激活数近似，M4 换断点表")
p.append("item  = 0    # 装备识别 M5")
p.append("trend = clamp(50 + mean_slope * 5, 0, 100)，slope = 近5回合血量平均每回合变化（掉血快分低）")
p.append("```")
p.append("")
p.append("输入 PlayerState.units 为 None -> 整体返回 None（诚实原则）；units 空 -> 各分量按 0 计。")
p.append("score < 0.45 的 UnitOnBoard 在入口统一剔除（A2，与感知 pending 阈值一致）。")
p.append("")
p.append("## 5. 模块(3) 对位预测 L0（matchup.py）")
p.append("")
p.append("```")
p.append("diff = my_power - opp_power            # 双方 None -> 返回 unknown 档（E6）")
p.append("winrate = 1 / (1 + exp(-0.08 * diff))  # sigmoid：diff 0->50%，+20->82%，-20->18%")
p.append("tier:   winrate >= 0.65 高 / 0.35-0.65 五五开 / < 0.35 低")
p.append("confidence: high  = 双方数据齐 且 |diff| >= 15")
p.append("            low   = 任一方数据缺 或 |diff| < 8")
p.append("            mid   = 其余")
p.append("```")
p.append("")
p.append("输出 MatchupPrediction(winrate, tier, confidence)，落库带 confidence 供四象限统计（A3）。")
p.append("k=0.08 为初始标定：典型分差 +-25 覆盖 12%-88% 区间；M6 回归重估。")
p.append("")
p.append("## 6. 模块(4) 影响推演（impact.py）")
p.append("")
p.append("输入：MatchupPrediction + 任务状态 TaskState(streak_type: win|lose|none, streak_count) + 快照。")
