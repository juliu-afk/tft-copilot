p.append("")
p.append("```")
p.append("@dataclass(frozen=True)")
p.append("class UnitOnBoard:        # 感知 UnitBox 的决策层投影（解耦：不依赖感知类型）")
p.append("    unit_id: str")
p.append("    cost: int")
p.append("    star: int | None      # None -> 一星基线（E4）")
p.append("    score: float          # 感知置信度，<0.45 的 pending 剔除（A2）")
p.append("")
p.append("@dataclass")
p.append("class BoardSnapshot:      # 自家回合快照（感知 -> 决策单入口）")
p.append("    round_no: int")
p.append("    scene: str")
